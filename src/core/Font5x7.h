// The glyph for c (lower case folds to upper), or null for a character the font does not hold.
inline const GlyphRow* Glyph5x7(char c) {
    const char up = static_cast<char>(c >= 'a' && c <= 'z' ? c - 32 : c);
    for (const GlyphRow& e : kFont5x7) {
        if (e.c == up) return &e;
    }
    return nullptr;
}

